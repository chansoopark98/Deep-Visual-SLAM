"""Plan v3 item 0.9 (C-N1): validate the GT-noise probe on synthetic data before trusting it on real trackers.

Truth = Savitzky-Golay-smoothed real test GT positions. Injected GT noise σ_g ∈ {0, 0.1, 0.2, 0.3} mm/axis.
Two synthetic depth-free trackers with independent noise plus, per scenario, an error component they share.
Real tracker residual patterns (0.6 DPVO, 0.7a KLT) do not exist yet; that run is deferred.

  python scripts/gt_noise_probe_validation.py     # writes reports/phase0/gt_noise_probe_validation.md
"""
import sys
from datetime import date
from pathlib import Path

import numpy as np
from scipy.signal import savgol_filter

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
from dvslam.data import redwood  # noqa: E402
from dvslam.eval.gt_noise_probe import estimate_sigma_g, probe_scene  # noqa: E402

OUT = REPO_ROOT / 'reports/phase0/gt_noise_probe_validation.md'
SIGMA_G_MM = (0.0, 0.1, 0.2, 0.3)
TOL_MM = 0.05
SEEDS = range(5)
SIGMA_A_MM, SIGMA_B_MM = 0.10, 0.15     # independent per-axis step noise of the two trackers
ESTIMATORS = ('intercept', 'k1', 'lag1')


def _segments(n: int, rng, share=0.05, length=30) -> np.ndarray:
    """Boolean mask of 'hard' frames: random 30-frame segments covering ~5 % of the sequence."""
    mask = np.zeros(n, bool)
    for s in rng.integers(0, n - length, size=max(1, int(share * n / length))):
        mask[s:s + length] = True
    return mask


def shared_error(kind: str, steps: np.ndarray, rng) -> np.ndarray:
    n = len(steps)
    if kind == 'independent':
        return np.zeros((n, 3))
    if kind == 'shared_white':            # both trackers see the same white error, 0.07 mm/axis
        return rng.normal(0, 0.07e-3, (n, 3))
    if kind == 'hard_bursts':             # hard segments: shared white error 0.3 mm/axis
        return rng.normal(0, 0.3e-3, (n, 3)) * _segments(n, rng)[:, None]
    if kind == 'hard_drift':              # hard segments: shared constant per-step bias 0.2 mm/axis
        m, out = _segments(n, rng), np.zeros((n, 3))
        edges = np.flatnonzero(np.diff(np.r_[0, m.astype(int)]) == 1)
        for s in edges:
            e = s + np.argmin(m[s:]) if not m[s:].all() else n
            out[s:e] = rng.normal(0, 0.2e-3, 3)
        return out
    if kind == 'shared_scale':            # common per-pair scale jitter 2 % (both under/over-shoot together)
        return steps * rng.normal(0, 0.02, n)[:, None]
    raise ValueError(kind)


SCENARIOS = ('independent', 'shared_white', 'hard_bursts', 'hard_drift', 'shared_scale')


def synthesize(truth: np.ndarray, sigma_g_m: float, scenario: str, rng) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """truth: (n+1, 3) smooth positions. Returns (steps_a, steps_b, noisy_gt_pos)."""
    steps = np.diff(truth, axis=0)
    shared = shared_error(scenario, steps, rng)
    a = steps + shared + rng.normal(0, SIGMA_A_MM * 1e-3, steps.shape)
    b = steps + shared + rng.normal(0, SIGMA_B_MM * 1e-3, steps.shape)
    return a, b, truth + rng.normal(0, sigma_g_m, truth.shape)


def smooth_truth(scenes=redwood.SCENES) -> list[np.ndarray]:
    return [savgol_filter(redwood.load_sequence(s, 'test').T_wc[:, :3, 3], 31, 3, axis=0) for s in scenes]


def run_cell(truths, sigma_g_mm, scenario, seed) -> dict:
    rng = np.random.default_rng(seed)
    probes = [probe_scene(*synthesize(t, sigma_g_mm * 1e-3, scenario, rng)) for t in truths]
    return estimate_sigma_g(probes)


def main():
    truths = smooth_truth()
    L = [f'# Phase 0 item 0.9 — GT-noise probe, synthetic validation ({date.today().isoformat()})', '',
         'Generated by `scripts/gt_noise_probe_validation.py`. Truth: Savitzky-Golay (31, 3) smoothed Redwood test GT '
         f'(5 scenes, 6,170 pairs). Trackers: independent per-axis step noise {SIGMA_A_MM} / {SIGMA_B_MM} mm plus a '
         f'shared component per scenario. {len(SEEDS)} seeds per cell. Pass = every seed within ±{TOL_MM} mm of σ_g.', '',
         'Scenarios: `independent` (no shared error); `shared_white` (0.07 mm/axis, every pair); `hard_bursts` '
         '(0.3 mm/axis white, in ~5 % of frames as 30-frame segments); `hard_drift` (0.2 mm/axis constant bias per '
         'segment, same segments); `shared_scale` (common 2 % per-pair scale jitter).', '',
         '| scenario | estimator | ' + ' | '.join(f'σ_g {s:.1f} mm' for s in SIGMA_G_MM) + ' | all pass |',
         '|---|---|' + '---|' * len(SIGMA_G_MM) + '---|']
    verdict = {}
    for sc in SCENARIOS:
        cells = {s: [run_cell(truths, s, sc, seed) for seed in SEEDS] for s in SIGMA_G_MM}
        for est in ESTIMATORS:
            row, ok_all = [], True
            for s in SIGMA_G_MM:
                vals = np.array([c[est] * 1e3 for c in cells[s]])
                ok = bool(np.all(np.abs(vals - s) <= TOL_MM))
                ok_all &= ok
                row.append(f'{vals.mean():.3f} (max err {np.abs(vals - s).max():.3f}) {"PASS" if ok else "FAIL"}')
            verdict[(sc, est)] = ok_all
            L.append(f'| {sc} | {est} | ' + ' | '.join(row) + f' | {"PASS" if ok_all else "FAIL"} |')
    passing = [e for e in ESTIMATORS if all(verdict[(sc, e)] for sc in SCENARIOS)]
    L += ['', '## Reading', '',
          f'- Estimators passing every scenario: {", ".join(passing) if passing else "none"}.',
          '- Failing cells show where the probe must not be trusted: a shared error that the stride/lag structure '
          'cannot separate from GT noise inflates or deflates σ̂.',
          '- The shared-error sizes above are assumptions, not measurements. `intercept` and `lag1` cancel shared '
          'errors that are white in time by construction; a time-correlated shared error (`hard_drift`) already biases '
          'them low at σ_g = 0.1 mm. Larger shared errors than assumed here can push them out of tolerance.',
          '- **Real-data run: deferred.** It needs the per-pair residuals of two depth-free trackers (0.6 DPVO, 0.7a KLT), '
          'which are out of this run\'s scope. When they exist, re-run this validation with their actual residual '
          'patterns (plan 0.9) before reading σ̂ on real GT. Until then G0-GT is not usable for the gate.', '']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
