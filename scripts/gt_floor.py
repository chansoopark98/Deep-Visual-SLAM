"""Validation stage V0: GT step statistics and a smoothing-based floor proxy for Redwood, TUM-VI and EuRoC.

For every sequence: number of pairs with measured GT, step-length percentiles, frame-to-frame roughness
(median |Δ‖step‖| / ‖step‖), and the item-03 MAPE between raw GT steps and the steps of Savitzky-Golay-smoothed
GT positions. The smoothing window is given in SECONDS so that 20 Hz and 30 Hz data are treated alike; the result
depends strongly on it, so two windows are reported. Smoothing also removes real motion, so these are upper-bound
proxies of the GT noise floor, not measurements of it (the tracker-based probe of plan T.3 is the measurement).

  DVSLAM_REDWOOD_ROOT=/home/park-ubuntu/park/datasets/redwood python scripts/gt_floor.py
"""
import argparse
import os
import sys
from datetime import date
from pathlib import Path

import numpy as np
from scipy.signal import savgol_filter

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
from dvslam.data import registry  # noqa: E402
from dvslam.eval.diagnostics import _pct_errors  # noqa: E402

WINDOWS_S = (0.35, 0.75)
MIN_STEP_M = 2e-3


def camera_steps(T_wc: np.ndarray, pos: np.ndarray) -> np.ndarray:
    """Steps of the camera centre expressed in the previous camera frame, (N-1, 3), metres."""
    return np.einsum('nji,nj->ni', T_wc[:-1, :3, :3], np.diff(pos, axis=0))


def sequence_stats(seq, fps: float) -> dict:
    pair_ok = getattr(seq, 'pair_valid', np.ones(len(seq) - 1, bool))
    pos = seq.T_wc[:, :3, 3]
    g = camera_steps(seq.T_wc, pos)
    n = np.linalg.norm(g, axis=1)
    both = pair_ok[:-1] & pair_ok[1:] & (n[:-1] > 1e-6)
    out = {'pairs': int(pair_ok.sum()), 'pairs_without_gt': int((~pair_ok).sum()),
           'step_p10_mm': float(np.percentile(n[pair_ok], 10) * 1e3), 'step_p50_mm': float(np.median(n[pair_ok]) * 1e3),
           'step_p90_mm': float(np.percentile(n[pair_ok], 90) * 1e3),
           'roughness_pct': float(np.median(np.abs(np.diff(n))[both] / n[:-1][both]) * 100)}
    for w in WINDOWS_S:
        k = int(round(w * fps)) | 1                      # odd number of frames closest to the window
        gs = camera_steps(seq.T_wc, savgol_filter(pos, k, 3, axis=0))
        out[f'smooth_{w}s_pct'] = float(_pct_errors(g[pair_ok], gs[pair_ok]).mean())
        moving = pair_ok & (n >= MIN_STEP_M)
        out[f'smooth_{w}s_min2mm_pct'] = float(_pct_errors(g[moving], gs[moving]).mean())
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', type=Path, default=REPO_ROOT / 'reports/v0/gt_floor.md')
    args = ap.parse_args()
    if 'DVSLAM_REDWOOD_ROOT' not in os.environ:
        sys.exit('set DVSLAM_REDWOOD_ROOT to the local Redwood copy (the built-in default is a slow network mount)')
    rows, missing = [], []
    for dataset in registry.DATASETS:
        fps, _ = registry.frame_rate(dataset)
        for split in (('train', 'validation', 'test') if dataset == 'tumvi' else ('validation', 'test')):
            present = registry.scenes(dataset, split)
            missing += [f'{dataset} {split} {m}' for m in registry.expected_scenes(dataset, split) if m not in present]
            for scene in present:
                s = sequence_stats(registry.load_sequence(dataset, scene, split, load_images=False), fps)
                rows.append((dataset, split, scene, s))
                print(dataset, split, scene, {k: round(v, 3) for k, v in s.items()})
    head = ['dataset', 'split', 'sequence', 'pairs', 'no GT', 'step p10 / p50 / p90 mm', 'roughness %']
    head += [f'smooth {w} s %' for w in WINDOWS_S] + [f'smooth {w} s, step ≥ 2 mm %' for w in WINDOWS_S]
    L = [f'# V0: GT step statistics and smoothing-based floor proxy ({date.today().isoformat()})', '',
         'Generated by `scripts/gt_floor.py`. Camera-centre steps between consecutive frames; pairs without measured',
         'GT at both ends are excluded. "smooth W s" = item-03 MAPE between raw GT steps and steps of',
         'Savitzky-Golay (order 3) smoothed GT positions with a W-second window.', '',
         'Limits of this proxy:',
         '- It is not a measurement of GT noise. Smoothing removes real motion (which raises the value) and lets part',
         '  of the GT noise through (which lowers it), and the value changes strongly with the window.',
         '- EuRoC machine-hall GT is itself a batch-smoothed estimate (Leica position + IMU), so its value is low by',
         '  construction and its orientation comes from the IMU alone.',
         '- GT time offset 0 is used for TUM-VI and EuRoC; the offset has not been measured (plan T.1).',
         '- Smoothing runs across GT dropouts that were bridged by interpolation, which affects pairs next to a gap.',
         '- Plan §11.2 quotes 53 mm, 3.7 % and 1.3 % for TUM-VI room1. The first two are IMU-origin values; at the',
         '  camera centre they are 56.9 mm and 4.0 %. The 1.3 % is not reproduced: it depends on the window.',
         f'- Sequences of the defined splits that are not on disk: {", ".join(missing) if missing else "none"}.', '',
         '| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for dataset, split, scene, s in rows:
        L.append(f'| {dataset} | {split} | {scene} | {s["pairs"]} | {s["pairs_without_gt"]} | '
                 f'{s["step_p10_mm"]:.2f} / {s["step_p50_mm"]:.2f} / {s["step_p90_mm"]:.2f} | {s["roughness_pct"]:.2f} | '
                 + ' | '.join(f'{s[f"smooth_{w}s_pct"]:.2f}' for w in WINDOWS_S) + ' | '
                 + ' | '.join(f'{s[f"smooth_{w}s_min2mm_pct"]:.2f}' for w in WINDOWS_S) + ' |')
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(args.out)


if __name__ == '__main__':
    main()
