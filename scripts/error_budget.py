"""Plan v3 item 0.3: baseline decomposition + 3-axis (σ∥, bias, jitter) item-03 simulation on real test GT steps.

  python scripts/error_budget.py            # writes reports/phase0/error_budget.md
"""
import csv
import sys
from datetime import date
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
from dvslam.eval import diagnostics as D  # noqa: E402

BASELINE = REPO_ROOT / 'baselines/pairs_eval/20261118-125421'
SCENES = ['apartment', 'bedroom', 'boardroom', 'lobby', 'loft']
OUT = REPO_ROOT / 'reports/phase0/error_budget.md'
INTERNAL_TARGET, OFFICIAL_LIMIT = 2.2, 2.96
REPS = 20


def load_baseline(scene):
    with open(BASELINE / f'{scene}_pose_errors.csv') as f:
        rows = list(csv.DictReader(f))
    g = np.array([[float(r[c]) for c in ('gt_tx', 'gt_ty', 'gt_tz')] for r in rows])
    p = np.array([[float(r[c]) for c in ('pred_tx', 'pred_ty', 'pred_tz')] for r in rows])
    return g, p


def main():
    data = {s: load_baseline(s) for s in SCENES}
    steps = [g for g, _ in data.values()]
    L = [f'# Phase 0 item 0.3 — item-03 error budget ({date.today().isoformat()})', '',
         'Generated by `scripts/error_budget.py`. GT steps: frozen baseline `20261118-125421` (Redwood test, 6,170 pairs).',
         f'Monte-Carlo: {REPS} repetitions per cell; value = mean over repetitions of the mean of 5 scene means.', '']

    L += ['## 1. Baseline decomposition (2026 PoseNet run, 40.06 %)', '',
          '| scene | MAPE % | median ‖pred‖/‖gt‖ | best global scale | MAPE after rescale % | σ∥ mm (std / robust) | pairs < 2 mm | their error share |',
          '|---|---|---|---|---|---|---|---|']
    pct_per_scene = []
    for s, (g, p) in data.items():
        pct = D._pct_errors(g, p)
        pct_per_scene.append(pct)
        sc, mr = D.best_rescale(g, p)
        sp = D.sigma_parallel(g, p)
        b = D.bin_contribution(g, p, edges_mm=(0, 2, np.inf))[0]
        L.append(f'| {s} | {pct.mean():.2f} | {D.median_step_ratio(g, p):.4f} | {sc:.3f} | {mr:.2f} | '
                 f'{sp["sigma_par_mm"]:.2f} / {sp["sigma_par_robust_mm"]:.2f} | {b["pair_share"]*100:.1f} % | '
                 f'{b["error_share"]*100:.1f} % |')
    pt, lo, hi = D.block_bootstrap_ci(pct_per_scene)
    L += ['', f'Item 03 = {pt:.4f} %, 95 % block-bootstrap CI [{lo:.2f}, {hi:.2f}] % (30-pair blocks, 1000 reps).',
          'Scale is roughly right (median ratio 0.89–1.12); the failure is per-pair noise of 2–5 mm along the motion.', '']

    L += ['## 2. Check against report 17 §5.3 (isotropic per-axis noise)', '',
          '| σ per axis (mm) | noise only % | + bias 1 % | + bias 2 % |', '|---|---|---|---|']
    for sig in (0.02, 0.05, 0.10, 0.20, 0.30):
        cells = [D.simulate_mape(steps, sig * 1e-3, b, reps=REPS)[0] for b in (0, 0.01, 0.02)]
        L.append(f'| {sig:.2f} | ' + ' | '.join(f'{c:.2f}' for c in cells) + ' |')
    L += ['', 'Report 17: 0.34 / 0.85 / 1.67 / 3.39 / 4.93 % (noise only); 1.95 % and 2.59 % at 0.10 mm with 1 % / 2 % bias.', '']

    L += ['## 3. Three-axis budget (σ∥ along the motion, common bias b, per-pair log-sd jitter)', '',
          f'Cell = item 03 %. Bold = ≤ {INTERNAL_TARGET} % internal target; † = over the {OFFICIAL_LIMIT} % official limit. '
          'Bias is applied as +b (over-estimated steps).', '']
    sig_grid, b_grid, j_grid = (0.05, 0.08, 0.10, 0.12, 0.15), (0, 0.005, 0.01, 0.015, 0.02), (0, 0.003, 0.01)
    results = {}
    for j in j_grid:
        L += [f'### jitter {j*100:.1f} % log-sd', '', '| σ∥ (mm) \\ b | ' + ' | '.join(f'{b*100:.1f} %' for b in b_grid) + ' |',
              '|---' * (len(b_grid) + 1) + '|']
        for sig in sig_grid:
            row = []
            for b in b_grid:
                m, _ = D.simulate_mape(steps, sig * 1e-3, b, j, noise='parallel', reps=REPS)
                results[(sig, b, j)] = m
                txt = f'{m:.2f}'
                row.append(f'**{txt}**' if m <= INTERNAL_TARGET else (f'{txt}†' if m > OFFICIAL_LIMIT else txt))
            L.append(f'| {sig:.2f} | ' + ' | '.join(row) + ' |')
        L.append('')

    m_alloc, sd_alloc = D.simulate_mape(steps, 0.10e-3, 0.01, 0.003, noise='parallel', reps=100)
    iso_vs_par = [(s, D.simulate_mape(steps, s * 1e-3, reps=100)[0],
                   D.simulate_mape(steps, s * 1e-3, noise='parallel', reps=100)[0]) for s in (0.05, 0.10, 0.20)]
    verdict = 'stays within' if m_alloc <= INTERNAL_TARGET else 'EXCEEDS'
    L += ['## 4. Verdict on the plan §2.2 allocation', '',
          f'(σ∥ = 0.10 mm, b = 1.0 %, jitter = 0.3 %): item 03 = **{m_alloc:.2f} % ± {sd_alloc:.2f}** (100 reps) → '
          f'{verdict} the {INTERNAL_TARGET} % internal target ({OFFICIAL_LIMIT - m_alloc:+.2f} %p to the official limit).', '',
          f'(σ∥ = 0.12 mm, b = 1.5 %, jitter = 0): {results[(0.12, 0.015, 0)]:.2f} % — plan calls this "conditional GO".', '',
          'Notes', '- σ∥ = σ_axis check (b = 0, jitter = 0, 100 reps), isotropic vs along-motion-only noise: '
          + '; '.join(f'{s:.2f} mm → {i:.3f} % vs {p:.3f} %' for s, i, p in iso_vs_par) + '.',
          '- Jitter is still per-pair in the increment; the depth-jitter limit is 0.3 % / κ, with κ measured in item 2.1.', '']

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(L))
    print(OUT)
    print('\n'.join(L[-9:]))


if __name__ == '__main__':
    main()
